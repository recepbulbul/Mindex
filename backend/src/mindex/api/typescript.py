"""TypeScript declarations from the API's OpenAPI schema (`mindex openapi`), no server needed.

The output, `frontend/src/api/generated.ts`, is committed. `frontend/src/api/contract.ts`
checks at compile time that it fits the hand-written `types.ts`, and CI regenerates it and
fails on any difference, so backend and frontend cannot drift apart silently.

`openapi-typescript` would do this too, but it needs TypeScript 5 and the frontend is on 7;
the schemas here are simple enough (objects, enums, arrays, nullable values and enum-keyed
maps) that a small generator is the smaller dependency.
"""

import json
import re
from collections.abc import Mapping
from typing import Any, cast

from fastapi import FastAPI

HEADER = (
    "// Generated by `uv run mindex openapi` from the backend's OpenAPI schema. Do not edit;\n"
    "// regenerate with `npm run gen:api`. contract.ts checks it against types.ts.\n"
)
REF = "#/components/schemas/"
IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")

Schema = Mapping[str, Any]


def _literal(value: Any) -> str:
    """A TypeScript literal in the frontend's Prettier style (single-quoted strings)."""
    if isinstance(value, str) and "'" not in value and "\\" not in value:
        return f"'{value}'"
    return json.dumps(value)


def _name(raw: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", raw)


def ts_type(schema: Schema) -> str:
    """The TypeScript type of one schema node."""
    if "$ref" in schema:
        return _name(str(schema["$ref"]).removeprefix(REF))
    if "const" in schema:
        return _literal(schema["const"])
    if "enum" in schema:
        return " | ".join(_literal(v) for v in cast(list[Any], schema["enum"]))
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = [ts_type(cast(Schema, s)) for s in cast(list[Any], schema[key])]
            return " | ".join(dict.fromkeys(parts))
    kind = schema.get("type")
    if kind == "array":
        item = ts_type(cast(Schema, schema.get("items", {})))
        return f"({item})[]" if " | " in item else f"{item}[]"
    if kind == "object":
        if "properties" in schema:
            return _object(schema, indent="  ")
        values = schema.get("additionalProperties")
        value = ts_type(cast(Schema, values)) if isinstance(values, dict) else "unknown"
        keys = schema.get("propertyNames")
        # Enum-keyed maps hold a subset of the keys (e.g. only an experiment's assets).
        if isinstance(keys, dict):
            return f"Partial<Record<{ts_type(cast(Schema, keys))}, {value}>>"
        return f"Record<string, {value}>"
    scalar = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}
    if kind == "null":
        return "null"
    return scalar.get(str(kind), "unknown")


def _object(schema: Schema, indent: str = "") -> str:
    props = cast(dict[str, Schema], schema.get("properties", {}))
    required = set(cast(list[str], schema.get("required", [])))
    lines = ["{"]
    for prop, sub in props.items():
        key = prop if IDENT.match(prop) else json.dumps(prop)
        optional = "" if prop in required else "?"
        lines.append(f"{indent}  {key}{optional}: {ts_type(sub)}")
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def declarations(openapi: Mapping[str, Any]) -> str:
    schemas = cast(dict[str, Schema], openapi.get("components", {}).get("schemas", {}))
    out = [HEADER]
    for raw in sorted(schemas):
        schema = schemas[raw]
        name = _name(raw)
        if schema.get("type") == "object" and "properties" in schema:
            out.append(f"export interface {name} {_object(schema)}\n")
        else:
            out.append(f"export type {name} = {ts_type(schema)}\n")
    return "\n".join(out)


def generate(app: FastAPI) -> str:
    return declarations(app.openapi())
